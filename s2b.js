// ================= QUIZ SYSTEM =================

let current = 0;
let score = 0;


const questionBox = document.getElementById("question");
const answersBox = document.getElementById("answers");
const scoreBox = document.getElementById("score");
const counterBox = document.getElementById("counter");


// LOAD QUESTION

function loadQuestion(){

    counterBox.innerHTML =
    `Question ${current + 1} / ${questions.length}`;

    questionBox.innerHTML =
    questions[current].question;

    answersBox.innerHTML="";


    questions[current].options.forEach(option=>{

        let button=document.createElement("button");

        button.className="option";

        button.innerHTML=option;


        button.onclick=function(){

            checkAnswer(button,option);

        };


        answersBox.appendChild(button);

    });

}


// CHECK ANSWER

function checkAnswer(button,selected){

    let allButtons =
    document.querySelectorAll(".option");


    allButtons.forEach(btn=>{
        btn.disabled=true;
    });


    if(selected === questions[current].answer){

        score++;

        button.classList.add("correct");

        fireworks();

    }
    else{

        button.classList.add("wrong");


        allButtons.forEach(btn=>{

            if(btn.innerHTML === questions[current].answer){

                btn.classList.add("correct");

            }

        });

    }


    scoreBox.innerHTML =
    "Score: " + score;

}


// NEXT QUESTION

function nextQuestion(){

    current++;


    if(current >= questions.length){


        let xp = score * 10;


const currentUser = localStorage.getItem("userEmail") || "Guest";


// SAVE USER SCORE

let oldScore = Number(
    localStorage.getItem(currentUser + "_totalScore")
) || 0;


let newScore = oldScore + score;


localStorage.setItem(
    currentUser + "_totalScore",
    newScore
);



// SAVE USER XP

let totalXP = Number(
    localStorage.getItem(currentUser + "_totalXP")
) || 0;


totalXP += xp;


localStorage.setItem(
    currentUser + "_totalXP",
    totalXP
);



// SAVE COMPLETED QUIZZES

let completed = Number(
    localStorage.getItem(currentUser + "_completedQuizzes")
) || 0;


localStorage.setItem(
    currentUser + "_completedQuizzes",
    completed + 1
);


        alert(
        "Quiz Completed!\n\nScore: "
        + score +
        "/" +
        questions.length +
        "\nXP Earned: "
        + xp
        );


        current=0;
        score=0;

    }


    loadQuestion();

}



// ================= FIREWORKS =================


const canvas =
document.getElementById("fireworks");

const ctx =
canvas.getContext("2d");


canvas.width =
window.innerWidth;

canvas.height =
window.innerHeight;


let particles=[];


function fireworks(){


for(let i=0;i<60;i++){


particles.push({

x:window.innerWidth/2,

y:window.innerHeight/3,

size:Math.random()*5+2,

speedX:(Math.random()-0.5)*8,

speedY:(Math.random()-0.5)*8,

life:100,

color:
[
"#00eaff",
"#ff0055",
"#ffff00",
"#00ff66"
]
[
Math.floor(Math.random()*4)
]


});


}


}



function animateFireworks(){


ctx.clearRect(
0,
0,
canvas.width,
canvas.height
);


particles.forEach((p,index)=>{


ctx.fillStyle=p.color;


ctx.beginPath();


ctx.arc(
p.x,
p.y,
p.size,
0,
Math.PI*2
);


ctx.fill();


p.x += p.speedX;

p.y += p.speedY;

p.life--;


if(p.life<=0){

particles.splice(index,1);

}


});


requestAnimationFrame(animateFireworks);


}


animateFireworks();


