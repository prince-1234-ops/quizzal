// ================= FIREWORKS =================


const canvas =
document.getElementById("fireworks");

const ctx =
canvas.getContext("2d");


canvas.width =
window.innerWidth;

canvas.height =
window.innerHeight;


let particles=[];


function fireworks(){


for(let i=0;i<60;i++){


particles.push({

x:window.innerWidth/2,

y:window.innerHeight/3,

size:Math.random()*5+2,

speedX:(Math.random()-0.5)*8,

speedY:(Math.random()-0.5)*8,

life:100,

color:
[
"#00eaff",
"#ff0055",
"#ffff00",
"#00ff66"
]
[
Math.floor(Math.random()*4)
]


});


}


}



function animateFireworks(){


ctx.clearRect(
0,
0,
canvas.width,
canvas.height
);


particles.forEach((p,index)=>{


ctx.fillStyle=p.color;


ctx.beginPath();


ctx.arc(
p.x,
p.y,
p.size,
0,
Math.PI*2
);


ctx.fill();


p.x += p.speedX;

p.y += p.speedY;

p.life--;


if(p.life<=0){

particles.splice(index,1);

}


});


requestAnimationFrame(animateFireworks);


}


animateFireworks();


